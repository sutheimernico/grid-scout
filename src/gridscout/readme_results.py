"""Render the README's results table from the report artifacts.

The README used to carry hand-copied numbers that drifted from the live
dashboard (MAE 15.25 vs 19.65 on the same day). The table between the markers
is now generated, so it can only say what the reports say — and it carries the
date of the run.
"""

import json
from pathlib import Path

START = "<!-- results:start -->"
END = "<!-- results:end -->"


def _run_date(report: dict) -> str:
    stamp = report.get("generated_utc")
    return f", run {stamp[:10]}" if stamp else ""


def _load(path: Path) -> dict | None:
    return json.loads(path.read_text()) if path.exists() else None


def render_results(reports_dir: Path) -> str:
    forecast = json.loads((reports_dir / "forecast_eval.json").read_text())
    battery = json.loads((reports_dir / "battery_backtest.json").read_text())
    agent = _load(reports_dir / "agent_eval.json")
    holdout = _load(reports_dir / "agent_eval_holdout.json")
    sensitivity = _load(reports_dir / "battery_sensitivity.json")

    period = forecast["eval_period"]
    pre_report = forecast["pre_auction"]
    pre = pre_report["models"]
    quant = forecast["quantiles"]
    rev = battery["revenue_eur_per_mw_year"]
    full = battery["full_model"]
    # One sample for every row: the pre-auction run covers slightly fewer hours than
    # the full-model run, so mixing the two reports would put two different naive
    # errors in one table.
    naive = pre["naive_yesterday"]["mae"]
    skill = pre_report["skill_vs_naive_pct"]
    full_mae = pre["lgbm_gate_closure"]["mae"]

    lines = [
        f"Run of {forecast['generated_utc'][:10]} (eval year {period['start']} – {period['end']}, "
        f"walk-forward, refit weekly, {pre_report['n']:,} hours). "
        "Regenerated by `uv run gridscout update-readme`.",
        "",
        "| What | MAE €/MWh |",
        "|---|---|",
        f"| Naive: yesterday's prices | {naive:.2f} |",
        f"| Seasonal naive: same weekday last week | {pre['seasonal_naive_7d']['mae']:.2f} |",
        f"| Per-hour ridge regression (LEAR-style linear baseline), pre-auction inputs | "
        f"{pre['ridge_pre_auction']['mae']:.2f} |",
        f"| **LightGBM, strictly pre-auction SMARD inputs only** (what exists at 12:00) | "
        f"**{pre['lgbm_pre_auction']['mae']:.2f}** ({skill:+.1f}% vs naive) |",
        f"| LightGBM with the TSOs' generation forecast for day D, which SMARD publishes "
        f"only after the auction (assumed known; a proxy for a commercial weather-based "
        f"forecast) | {full_mae:.2f} ({(naive - full_mae) / naive:+.1%} vs naive) |",
        "",
        f"- **p10–p90 band (full model):** raw coverage {quant['coverage_p10_p90']:.0%}, "
        f"{quant['conformal']['coverage_p10_p90']:.0%} after walk-forward conformal "
        "calibration (target 80%).",
        f"- **Battery (1 MW / 2 MWh), annualised from {battery['n_days']} days:** the "
        f"pre-auction forecast adds **{battery['model_edge_over_naive_eur_per_mw_year']:+,.0f} "
        f"€/MW/yr** over a naive forecast (gross, no fees or degradation); revenue "
        f"{rev['model']:,.0f} €/MW/yr ({battery['capture_rate_model']:.1%} of perfect foresight) "
        f"against {rev['naive']:,.0f} for naive: most of it is the battery, not the forecast. "
        f"With the full model's forecast the edge would be "
        f"{full['model_edge_over_naive_eur_per_mw_year']:+,.0f} €/MW/yr "
        f"({full['capture_rate_model']:.1%} of perfect foresight).",
    ]
    if sensitivity:
        edges = [c["model_edge_over_naive_eur_per_mw_year"] for c in sensitivity.get("cells", [])]
        if edges:
            lines.append(
                f"- Across the efficiency × duration sweep (pre-auction forecast) the edge over "
                f"naive stays between "
                f"{min(edges):,.0f} and {max(edges):,.0f} €/MW/yr."
            )
    if agent:
        lines.append(
            f"- **Local agent, development set** (tuned on): {agent['passed']}/{agent['n']} "
            f"({agent['pass_rate']:.0%}{_run_date(agent)})."
        )
    if holdout:
        lines.append(
            f"- **Local agent, untuned holdout** (written after tuning): "
            f"{holdout['passed']}/{holdout['n']} ({holdout['pass_rate']:.0%}{_run_date(holdout)})."
        )
    return "\n".join(lines)


def update_readme(readme: Path, reports_dir: Path) -> bool:
    """Replace the block between the markers; returns True when the file changed."""
    text = readme.read_text()
    if START not in text or END not in text:
        raise ValueError(f"{readme} has no {START} ... {END} block")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    new = f"{head}{START}\n{render_results(reports_dir)}\n{END}{tail}"
    changed = new != text
    if changed:
        readme.write_text(new)
    return changed
